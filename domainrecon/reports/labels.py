def norm_lang(lang: str | None) -> str:
    """Langue prise en charge (fr ou en), sinon le français."""
    return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG


def tr(lang: str, key: str, **params) -> str:
    """Libellé `key` dans `lang` ; la clé elle-même si elle manque."""
    template = LABELS[norm_lang(lang)].get(key) or LABELS[DEFAULT_LANG].get(key) or key
    return template.format(**params) if params else template
